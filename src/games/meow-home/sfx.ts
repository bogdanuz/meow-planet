export function createSfx(audio: AudioManager) {
  const timers = new Set<ReturnType<typeof setTimeout>>()
  return {
    play(id: SfxId): void {
      for (const [freq, at, durationSec, gain] of PATTERNS[id]) {
        const t = setTimeout(() => {
          timers.delete(t)
          void audio.playTone(freq, { channel: 'sfx', durationSec, gain })
        }, at)
        timers.add(t)
      }
    },
    stop(): void {
      for (const t of timers) clearTimeout(t)
      timers.clear()
    },
  }
}

export type Sfx = ReturnType<typeof createSfx>
